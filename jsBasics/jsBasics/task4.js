const radiusCircle = 5;
const circleArea = Math.PI * Math.pow(radiusCircle, 2);

console.log("Площа кола:", circleArea.toFixed(2));


const length = 10;
const width = 4.5;
const rectangleArea = length * width;

console.log("Площа прямокутника:", rectangleArea.toFixed(2));

const radiusCylinder = 3;
const heightCylinder = 7;
const cylinderVolume = Math.PI * Math.pow(radiusCylinder, 2) * heightCylinder;

console.log("Об'єм циліндра:", cylinderVolume.toFixed(2));